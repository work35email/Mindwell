def _build() -> dict[str, dict[str, str]]:
    catalogs = {"en": {}, "si": {}, "ta": {}}
    for key, en, si, ta in _ROWS:
        catalogs["en"][key] = en
        catalogs["si"][key] = si
        catalogs["ta"][key] = ta
    return catalogs


STRINGS = _build()


def show_text(raw: str) -> str:
    """Return one language from a stored {en, si, ta} note. Plain text is unchanged."""
    if not raw or not raw.lstrip().startswith("{"):
        return raw
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return raw
    if not isinstance(data, dict) or not any(key in data for key in ("en", "si", "ta")):
        return raw
    lang = current_language()
    value = data.get(lang) or data.get("en")
    return value if isinstance(value, str) else raw


def current_language() -> str:
    try:
        from flask import has_request_context, session
        from flask_login import current_user
    except ImportError:
        return "en"
    if not has_request_context():
        return "en"
    if getattr(current_user, "is_authenticated", False) and getattr(current_user, "language", None) in STRINGS:
        return current_user.language
    chosen = session.get("lang")
    if chosen in STRINGS:
        return chosen
    return "en"


def t(key: str, lang: str | None = None, **kwargs) -> str:
    chosen = lang if lang in STRINGS else current_language()
    text = STRINGS.get(chosen, STRINGS["en"]).get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text
